"""exp's structured family: the windows of arguments next to an exact case,
which the in-lane test marks and a replay decides (docs/studies/M1-exp-log.md,
section 3.5; Logan's decision on question 4: keep the marks, list the
windows' centres in the tests).

WHY THERE IS A FAMILY. Near 0, exp(x) = 1 + x + x^2/2 + .... Where 1 + x is
a rounding boundary of the result - a midpoint under rne and rmm, a grid
point under the directed three - the true value sits x^2/2 from it, which
is less than the bound Bv = 2^-(p+G) of the double word's V for x under
about 2^-((p+G)/2). The in-lane test cannot decide such a lane; it marks it.
The arguments are x = +-c 2^-e, c a small integer, e from about (p + G)/2 up
to p: at the study's G = 46 four exponents at fp64, 34 at fp128 and 96 at
fp256 (its 3.5); at fp64's decided G = 44, e = 49 to 54 (the committed list
below). fp32 has none at G = 40, where (p + G)/2 = 32 is past p = 24 and the
tiny gate (|x| < 2^-(p+3), decided by the side of 1) takes the rest.

EACH IS A CENTRE. A neighbour x + j ulp(x) moves the true value by about
j ulp(x), so it is marked too while that stays inside the bound: the window
is 2 Bv wide, about 2 W ulps, W = Bv / ulp(x) = 2^(e - G - 1) for x about
2^-e. At fp256 a window holds about 2^190 arguments.

THE THEORY, independent of the fragment. For an argument x and an
attribute, d(x) is the distance from exp(x), mpmath at 4p + 200 bits, to
the nearest rounding boundary of the result, in units of the nominal bound
2^-(p+G) exp(x). The routine marks a lane when its interval V +- Bv
straddles a boundary, and V is within about 2^-2.6 Bv of exp(x) at fp64 and
less elsewhere (the budget, mathlib_budget), so:

  d < 0.7        the lane MUST be marked;
  d > 1.3        the lane must NOT be marked, and is right unmarked;
  between        either: if marked, its guess is counted, not judged;
  |x| < 2^-(p+3) never marked: transcend.py decides it by the side of 1.

THE COMMITTED LIST (FAMILY, at the end of this file) is the centres: for
each format and attribute, the arguments of the study's census - x = c 2^-e,
a signed integer c with |c| <= 16, e from p - 10 to p + 3, each distinct
value once - whose d is under 0.7. It is GENERATED by generate(), from the
theory alone, and test_mathlib.py holds the committed list to a fresh
generation, so it can neither go stale nor be edited by hand to agree with a
fault. The tests then run the fragment on each centre and on its neighbours:
inside the window (d < 0.7 by the theory, at offsets of 1, W/8, W/4 and
0.65 W ulps either side) and outside (1.35 W, 2 W, 8 W and 1024 W), on the
census arguments that are not centres and, at fp128 and fp256, on the DEEP
arguments (deep_arguments): the exponents between the first a window can
start at, (p + G)/2, and the census's lowest, which the census does not
reach and where the bound's calibration shows.

    python python/tests/mathlib_runs.py family --write     regenerate FAMILY
"""

import functools
import math
import sys
from fractions import Fraction
from pathlib import Path

import mpmath

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from cft_golden import mathlib as ml  # noqa: E402
from cft_golden import softfloat as sf  # noqa: E402

MUST_MARK = 0.7
MUST_NOT = 1.3
RND_NAMES = sf.RND_NAMES
# (label, multiple of W in ulps; None for exactly one ulp): the first
# N_INSIDE inside a window, the rest outside it. 0.65 W and 1.35 W sit just
# inside the theory's two thresholds (d < 0.7 must mark, d > 1.3 must not):
# they pin the bound's calibration, a bound half as wide leaves the first
# unmarked and one twice as wide marks the second.
OFFSETS = (("1", None), ("W/8", Fraction(1, 8)), ("W/4", Fraction(1, 4)),
           ("0.65W", Fraction(13, 20)), ("1.35W", Fraction(27, 20)),
           ("2W", Fraction(2)), ("8W", Fraction(8)), ("1024W", Fraction(1024)))
N_INSIDE = 4


def census(fmt):
    """The study's census (census.py): {bits: (c, e)}, x = c 2^-e for a
    signed integer c with |c| <= 16, e from p - 10 to p + 3, each distinct
    value once, in its smallest-|c| form."""
    p = fmt.prec
    out = {}
    for e in range(p - 10, p + 4):
        for c in range(1, 17):
            for s in (0, 1):
                bits, fl = sf.round_pack(fmt, s, c, -e, sf.RND_RNE)
                if fl == 0 and bits not in out:
                    out[bits] = (-c if s else c, e)
    return out


def _mp(q):
    return mpmath.mpf(q.numerator) / q.denominator


def distance(fmt, rnd, x, G=None):
    """d(x): the distance from exp(x) to the nearest rounding boundary of
    the result under rnd - midpoints under rne and rmm, grid points under
    the directed three - in units of 2^-(p+G) exp(x). By mpmath."""
    p = fmt.prec
    G = ml.GUARD[fmt.name] if G is None else G
    with mpmath.workprec(4 * p + 200):
        T = mpmath.exp(_mp(ml._dec(fmt, x)))
        e = mpmath.mag(T) - 1                       # floor(log2 T)
        ulp = mpmath.mpf(2) ** (e - p + 1)
        q = T / ulp
        frac = q - mpmath.floor(q)
        if rnd in (sf.RND_RNE, sf.RND_RMM):
            dist = abs(frac - mpmath.mpf(1) / 2) * ulp
        else:
            dist = min(frac, 1 - frac) * ulp
        return float(dist / (mpmath.mpf(2) ** (-(p + G)) * T))


def is_gated(fmt, x):
    """Below 2^-(p+3): transcend.py decides it by the side of 1 alone."""
    return abs(ml._dec(fmt, x)) < Fraction(1, 2 ** (fmt.prec + 3))


def classify(fmt, rnd, x, G=None):
    """"mark", "clear", "either" or "gated": what the theory demands of
    the routine on x."""
    if is_gated(fmt, x):
        return "gated"
    d = distance(fmt, rnd, x, G)
    return "mark" if d < MUST_MARK else "clear" if d > MUST_NOT else "either"


@functools.lru_cache(maxsize=None)
def centres(fmt, rnd):
    """[(c, e)]: the census arguments c 2^-e the theory demands marked, by
    exponent, then |c|, then sign."""
    out = []
    for bits, (c, e) in sorted(census(fmt).items(),
                               key=lambda kv: (kv[1][1], abs(kv[1][0]),
                                               kv[1][0] < 0)):
        if classify(fmt, rnd, bits) == "mark":
            out.append((c, e))
    return out


def argument(fmt, centre):
    """The encoding of c 2^-e."""
    c, e = centre
    return sf.round_pack(fmt, 1 if c < 0 else 0, abs(c), -e,
                         sf.RND_RNE)[0]


def half_width(fmt, x, G=None):
    """W: the bound's width in ulps of x, Bv / ulp(x) for exp(x) about 1
    (so 2^-(p+G) / ulp(x), ulp(x) = 2^(floor(log2 |x|) - p + 1))."""
    p = fmt.prec
    G = ml.GUARD[fmt.name] if G is None else G
    u = sf.unpack(fmt, x)
    lead = u.m.bit_length() - 1 + u.e              # floor(log2 |x|)
    return Fraction(2) ** (-(p + G)) / Fraction(2) ** (lead - p + 1)


def neighbours(fmt, centre, G=None):
    """[(bits, label)]: the centre's neighbours in the encoding, either side,
    at OFFSETS: the first N_INSIDE inside its window, the rest outside."""
    x0 = argument(fmt, centre)
    W = half_width(fmt, x0, G)
    sign, mag0 = x0 & fmt.sign_mask, x0 & ~fmt.sign_mask
    out = []
    for lab, mult in OFFSETS:
        j = 1 if mult is None else max(1, math.ceil(W * mult))
        for sgn in (1, -1):
            mag = mag0 + sgn * j
            if 0 < mag < fmt.exp_mask << fmt.man_w:
                out.append((sign | mag, f"{'+' if sgn > 0 else '-'}{lab}"))
    return out


def deep_arguments(fmt, G=None):
    """[(bits, label)]: x = c 2^-e for c = 1, 3, 5, both signs, and e from
    three under the first exponent a window can start at, (p + G)/2, up to
    p - 11: the exponents between there and the census's lowest, p - 10. At
    fp64 the census starts below (43 against 46) and there are none; fp128
    has 26 exponents of them and fp256 88. The theory puts the windows'
    lower edge at the first of them, so these lanes pin the bound to it:
    a bound half as wide leaves the window's inner half unmarked, one twice
    as wide marks lanes the theory puts outside."""
    p = fmt.prec
    G = ml.GUARD[fmt.name] if G is None else G
    out = []
    for e in range(-(-(p + G) // 2) - 3, p - 10):
        for c in (1, 3, 5):
            for s in (1, -1):
                out.append((argument(fmt, (s * c, e)), f"{s * c} 2^-{e}"))
    return out


def generate(formats=None):
    """FAMILY, all of it, from the theory: {format: {attribute: [(c, e)]}}
    (the committed list below is held to this)."""
    out = {}
    for fmt in formats or ml.FORMATS:
        out[fmt.name] = {RND_NAMES[r]: centres(fmt, r)
                         for r in sf.RND_MODES}
    return out


# The line that starts the generated tail of this file. Built from two
# pieces so that this line does not itself contain it.
_MARKER = ("# ---- GENERATED by "
           + "python/tests/mathlib_runs.py family --write")
NL = chr(10)


def render(data):
    """The generated tail of this file: FAMILY as text, each distinct list
    of centres written once and named by every attribute that has it."""
    out = [_MARKER + ": centres",
           "#",
           "# {format: {attribute: [(c, e)]}}: the census arguments c 2^-e (a",
           "# signed integer c, |c| <= 16) whose exp lies within 0.7 of the",
           "# nominal bound of a rounding boundary under that attribute. The",
           "# directed three share their boundaries, and so do rne and rmm.",
           "# fp32 has none: at G = 40 its windows are empty.",
           ""]
    names = {}
    for fmt_name, per in data.items():
        for lst in per.values():
            key = (fmt_name, tuple(lst))
            if key in names:
                continue
            names[key] = f"_{fmt_name.upper()}_{len(names) + 1}"
            if not lst:
                out.append(f"{names[key]} = []")
                continue
            lines, line = [], "    "
            for c, e in lst:
                tok = f"({c}, {e}),"
                if len(line) + len(tok) + 1 > 78:
                    lines.append(line.rstrip())
                    line = "    "
                line += tok + " "
            lines.append(line.rstrip())
            out.append(f"{names[key]} = [" + NL + NL.join(lines) + NL + "]")
    out += ["", "FAMILY = {"]
    for fmt_name, per in data.items():
        out.append(f'    "{fmt_name}": {{')
        for rnd_name, lst in per.items():
            ref = names[(fmt_name, tuple(lst))]
            out.append(f'        "{rnd_name}": {ref},')
        out.append("    },")
    out.append("}")
    return NL.join(out) + NL


def write(path=None):
    """Regenerate FAMILY into this file (everything from the marker line)."""
    path = Path(path or __file__)
    text = path.read_text(encoding="utf-8")
    head = text[:text.index(_MARKER)]
    path.write_text(head + render(generate()), encoding="utf-8", newline=NL)


