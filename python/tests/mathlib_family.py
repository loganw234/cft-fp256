"""The structured families of exp and expm1, and exp2's lack of one: the
windows of arguments next to an exact case, which the in-lane test marks and
a replay decides (docs/studies/M1-exp-log.md, section 3.5; Logan's decision on
question 4: keep the marks, list the windows' centres in the tests).

WHY THERE IS A FAMILY. Near 0, exp(x) = 1 + x + x^2/2 + .... Where 1 + x is
a rounding boundary of the result - a midpoint under rne and rmm, a grid
point under the directed three - the true value sits x^2/2 from it, which
is less than the bound Bv = 2^-(p+G) of the double word's V for x under
about 2^-((p+G)/2). The in-lane test cannot decide such a lane; it marks it.
The arguments are x = +-c 2^-e, c a small integer, e from about (p + G)/2 up
to p: at the study's G = 46 four exponents at fp64, 34 at fp128 and 96 at
fp256 (its 3.5); at fp64's decided G = 44, e = 49 to 54 (the committed list
below). fp32 has none at G = 40, where (p + G)/2 = 32 is past p = 24 and the
tiny gate (|x| < 2^-(p+3), decided by the side of 1) takes the rest.

expm1 has the same family, x = +-c 2^-e, for the same reason: expm1(x) =
x + x^2/2 + ..., and x itself is a float, a grid point of the result, so the
true value sits x^2/2 from a grid point and, for e about p, a fraction of a
cell from a midpoint (its census: the study's 3.5). Its bound is relative to
|V|, about |x|, so the family starts at the same exponents (the gate is
|x| < 2^-(p+2)).

expm1 has a second family, which the study's census did not contain and
parcel MB1 found in the pools' edges: x near -n ln 2. There e^x is near 2^-n,
so expm1(x) = -1 + 2^-n (1 + eps) with eps the rounding of x (about 2^-p |x|):
for n <= p the value is a grid point -1 + 2^-n, the directed attributes'
boundary, and for n = p + 1 the midpoint -1 + 2^-(p+1) between -1 and the next
float, the boundary of rne and rmm. The bound is relative to |V|, about 1, so
the true value is within it of the boundary when 2^-n |eps| is under
2^-(p+G): for n from about G + log2 n up to p + 1. x = RN(-n ln 2) is the
centre of such a window ("n", n) in the list below.

exp2 has no family: 2^x = 2^N (1 + x' ln 2 + ...) for x = N + x', and ln 2 is
irrational, so a float x' puts the value at a position inside the cell that is
not the exact one the structure needs (the study's 3.5; the census marks none,
and the theory below agrees at every format and attribute).

EACH IS A CENTRE. A neighbour x + j ulp(x) moves the true value, or the boundary
it is next to, by about j ulp(x) (exp, and expm1's second family) or by
j x ulp(x) (expm1's first, where the boundary x moves with it), so it is
marked too while that stays inside the bound: the window is 2 Bv wide, about
2 W ulps of x (half_width()). At fp256 a window holds about 2^190 arguments.

THE THEORY, independent of the fragment. For an argument x and an
attribute, d(x) is the distance from f(x), mpmath at 4p + 200 bits, to
the nearest rounding boundary of the result, in units of the nominal bound
2^-(p+G) |f(x)|. The routine marks a lane when its interval V +- Bv
straddles a boundary, and V is within about 2^-2.6 Bv of f(x) at fp64 and
less elsewhere (the budget, mathlib_budget), so:

  d < 0.7        the lane MUST be marked;
  d > 1.3        the lane must NOT be marked, and is right unmarked;
  between        either: if marked, its guess is counted, not judged;
  gated          never marked: |x| < 2^-(p+3) for exp and exp2, |x| < 2^-(p+2)
                 for expm1 (transcend.py decides it by the side of 1 or of x),
                 an integer x at exp2 (2^x is exact, with no flag), or a
                 screen answers it.

THE COMMITTED LIST (FAMILY, at the end of this file) is the centres: for each
routine, format and attribute, the arguments of the study's census - x = c 2^-e,
a signed integer c with |c| <= 16, e from p - 10 to p + 3, each distinct
value once - and, for expm1, of the second family's census, x = RN(-n ln 2) for
n = 1 to p + 2, whose d is under 0.7. It is GENERATED by generate(), from the
theory alone, and test_mathlib.py holds the committed list to a fresh
generation, so it can neither go stale nor be edited by hand to agree with a
fault. The tests then run the fragment on each centre and on its neighbours:
inside the window (d < 0.7 by the theory, at offsets of 1, W/8, W/4 and
0.65 W ulps either side) and outside (1.35 W, 2 W, 8 W and 1024 W), on the
census arguments that are not centres and, at fp128 and fp256, on the DEEP
arguments (deep_arguments): the exponents between the first a window can
start at, (p + G)/2, and the census's lowest, which the census does not
reach and where the bound's calibration shows.

    python python/tests/mathlib_runs.py family --write     regenerate FAMILY
"""

