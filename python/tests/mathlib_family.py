from cft_golden import mathlib as ml  # noqa: E402
from cft_golden import softfloat as sf  # noqa: E402

MUST_MARK = 0.7
MUST_NOT = 1.3
RND_NAMES = sf.RND_NAMES
FUNCTIONS = ml.NAMES                    # exp, exp2, expm1
# (label, multiple of W in ulps; None for exactly one ulp): the first
# N_INSIDE inside a window, the rest outside it. 0.65 W and 1.35 W sit just
# inside the theory's two thresholds (d < 0.7 must mark, d > 1.3 must not):
# they pin the bound's calibration, a bound half as wide leaves the first
# unmarked and one twice as wide marks the second.
OFFSETS = (("1", None), ("W/8", Fraction(1, 8)), ("W/4", Fraction(1, 4)),
           ("0.65W", Fraction(13, 20)), ("1.35W", Fraction(27, 20)),
           ("2W", Fraction(2)), ("8W", Fraction(8)), ("1024W", Fraction(1024)))
N_INSIDE = 4


def census(fmt):
    """The study's census (census.py): {bits: (c, e)}, x = c 2^-e for a
    signed integer c with |c| <= 16, e from p - 10 to p + 3, each distinct
    value once, in its smallest-|c| form."""
    p = fmt.prec
    out = {}
    for e in range(p - 10, p + 4):
        for c in range(1, 17):
            for s in (0, 1):
                bits, fl = sf.round_pack(fmt, s, c, -e, sf.RND_RNE)
                if fl == 0 and bits not in out:
                    out[bits] = (-c if s else c, e)
    return out


def census_n(fmt):
    """expm1's second family's census: {bits: ("n", n)}, x = RN(-n ln 2) for
    n = 1 to p + 2 (n = p + 2 is the clamp's own edge: the float is one of
    the two nearest the screen)."""
    return {argument(fmt, ("n", n)): ("n", n) for n in range(1, fmt.prec + 3)}


def _mp(q):
    return mpmath.mpf(q.numerator) / q.denominator


def _value(fn, xv):
    if fn == "exp":
        return mpmath.exp(xv)
    if fn == "expm1":
        return mpmath.expm1(xv)
    return mpmath.power(2, xv)


@functools.lru_cache(maxsize=None)
def _fraction_in_cell(fn, fmt, x):
    """(frac, ulp relative to |f(x)|, 1/|f(x)|): where |f(x)| lies in its
    rounding cell, by mpmath at 4p + 200 bits, as a float pair for the two
    boundary kinds; cached, since the attributes share it."""
    p = fmt.prec
    with mpmath.workprec(4 * p + 200):
        T = abs(_value(fn, _mp(ml._dec(fmt, x))))
        e = mpmath.mag(T) - 1                       # floor(log2 T)
        ulp = mpmath.mpf(2) ** (e - p + 1)
        q = T / ulp
        frac = q - mpmath.floor(q)
        return (float(abs(frac - mpmath.mpf(1) / 2) * ulp / T),     # midpoint
                float(min(frac, 1 - frac) * ulp / T))               # grid point


def distance(fmt, rnd, x, G=None, fn="exp"):
    """d(x): the distance from f(x) to the nearest rounding boundary of
    the result under rnd - midpoints under rne and rmm, grid points under
    the directed three - in units of 2^-(p+G) |f(x)|. By mpmath."""
    p = fmt.prec
    G = ml.GUARD[fmt.name] if G is None else G
    mid, grid = _fraction_in_cell(fn, fmt, x)
    d = mid if rnd in (sf.RND_RNE, sf.RND_RMM) else grid
    return d / 2.0 ** (-(p + G))


def is_gated(fmt, x, fn="exp"):
    """Never marked: below 2^-(p+3) (exp, exp2) or 2^-(p+2) (expm1), where
    transcend.py decides by the side of 1 or of x; or answered by a screen
    (the overflow and underflow of exp and exp2, expm1's clamp to -1 and its
    overflow), which also keeps the theory from asking mpmath for e^x at an
    argument as large as the format holds."""
    xv = ml._dec(fmt, x)
    p = fmt.prec
    if fn == "exp2":
        hi, lo = Fraction(fmt.emax + 1), Fraction(fmt.emin - p)
    else:
        hi = ml._dec(fmt, ml._screens(fmt)[0])
        lo = ml._dec(fmt, ml._screen_expm1(fmt) if fn == "expm1"
                     else ml._screens(fmt)[1])
    tiny = Fraction(1, 2 ** (p + (2 if fn == "expm1" else 3)))
    if fn == "exp2" and xv.denominator == 1:
        return True             # an integer: 2^x is exact, decided exactly
    return abs(xv) < tiny or xv <= lo or xv >= hi


def classify(fmt, rnd, x, G=None, fn="exp"):
    """"mark", "clear", "either" or "gated": what the theory demands of
    the routine on x."""
    if is_gated(fmt, x, fn):
        return "gated"
    d = distance(fmt, rnd, x, G, fn)
    return "mark" if d < MUST_MARK else "clear" if d > MUST_NOT else "either"


@functools.lru_cache(maxsize=None)
def centres(fmt, rnd, fn="exp"):
    """[centre]: the census arguments the theory demands marked, by
    exponent, then |c|, then sign, as (c, e) for c 2^-e; and for expm1 the
    second family's, as ("n", n) for RN(-n ln 2), by n. exp2's is empty
    wherever the theory says so (it does at every format and attribute)."""
    out = []
    for bits, (c, e) in sorted(census(fmt).items(),
                               key=lambda kv: (kv[1][1], abs(kv[1][0]),
                                               kv[1][0] < 0)):
        if classify(fmt, rnd, bits, None, fn) == "mark":
            out.append((c, e))
    if fn == "expm1":
        for bits, (_n, n) in sorted(census_n(fmt).items(),
                                    key=lambda kv: kv[1][1]):
            if classify(fmt, rnd, bits, None, fn) == "mark":
                out.append(("n", n))
    return out


def argument(fmt, centre):
    """The encoding of a centre: c 2^-e for (c, e); RN(-n ln 2) for
    ("n", n)."""
    a, b = centre
    if a == "n":
        return ml._enc(fmt, -b * ml._ln2())
    return sf.round_pack(fmt, 1 if a < 0 else 0, abs(a), -b, sf.RND_RNE)[0]


def half_width(fmt, x, G=None, centre=None):
    """W: the window's half width in ulps of x. For exp's centres and
    expm1's first family it is Bv / ulp(x) for f(x) about 1 (exp) or about
    |x| (expm1; the boundary x moves with it, so the drift per ulp is
    x ulp(x) against Bv = 2^-(p+G) |x|): 2^-(p+G) / ulp(x), ulp(x) =
    2^(floor(log2 |x|) - p + 1). For expm1's second family, ("n", n),
    f(x) = -1 + 2^-n (1 + eps) moves by 2^-n ulp(x) an ulp while the boundary
    stays, against Bv = 2^-(p+G): 2^(n - p - G) / ulp(x)."""
    p = fmt.prec
    G = ml.GUARD[fmt.name] if G is None else G
    u = sf.unpack(fmt, x)
    lead = u.m.bit_length() - 1 + u.e              # floor(log2 |x|)
    if centre is not None and centre[0] == "n":
        return Fraction(2) ** (centre[1] - G - lead - 1)
    return Fraction(2) ** (-(p + G)) / Fraction(2) ** (lead - p + 1)


def neighbours(fmt, centre, G=None):
    """[(bits, label)]: the centre's neighbours in the encoding, either side,
    at OFFSETS: the first N_INSIDE inside its window, the rest outside."""
    x0 = argument(fmt, centre)
    W = half_width(fmt, x0, G, centre)
    sign, mag0 = x0 & fmt.sign_mask, x0 & ~fmt.sign_mask
    out = []
    for lab, mult in OFFSETS:
        j = 1 if mult is None else max(1, math.ceil(W * mult))
        for sgn in (1, -1):
            mag = mag0 + sgn * j
            if 0 < mag < fmt.exp_mask << fmt.man_w:
                out.append((sign | mag, f"{'+' if sgn > 0 else '-'}{lab}"))
    return out


def deep_arguments(fmt, G=None):
    """[(bits, label)]: x = c 2^-e for c = 1, 3, 5, both signs, and e from
    three under the first exponent a window can start at, (p + G)/2, up to
    p - 11: the exponents between there and the census's lowest, p - 10. At
    fp64 the census starts below (43 against 46) and there are none; fp128
    has 26 exponents of them and fp256 88. The theory puts the windows'
    lower edge at the first of them, so these lanes pin the bound to it:
    a bound half as wide leaves the window's inner half unmarked, one twice
    as wide marks lanes the theory puts outside."""
    p = fmt.prec
    G = ml.GUARD[fmt.name] if G is None else G
    out = []
    for e in range(-(-(p + G) // 2) - 3, p - 10):
        for c in (1, 3, 5):
            for s in (1, -1):
                out.append((argument(fmt, (s * c, e)), f"{s * c} 2^-{e}"))
    return out


def generate(formats=None):
    """FAMILY, all of it, from the theory: {routine: {format: {attribute:
    [centre]}}} (the committed list below is held to this)."""
    out = {}
    for fn in FUNCTIONS:
        out[fn] = {}
        for fmt in formats or ml.FORMATS:
            out[fn][fmt.name] = {RND_NAMES[r]: centres(fmt, r, fn)
                                 for r in sf.RND_MODES}
    return out


# The line that starts the generated tail of this file. Built from two
# pieces so that this line does not itself contain it.
_MARKER = ("# ---- GENERATED by "
           + "python/tests/mathlib_runs.py family --write")
NL = chr(10)


def _token(centre):
    a, b = centre
    return f"({a!r}, {b})," if isinstance(a, str) else f"({a}, {b}),"


def render(data):
    """The generated tail of this file: FAMILY as text, each distinct list
    of centres written once and named by every routine, format and attribute
    that has it."""
    out = [_MARKER + ": centres",
           "#",
           "# {routine: {format: {attribute: [centre]}}}: a centre is (c, e),",
           "# the census argument c 2^-e (a signed integer c, |c| <= 16), or",
           "# (\"n\", n), expm1's RN(-n ln 2), whose f lies within 0.7 of the",
           "# nominal bound of a rounding boundary under that attribute. The",
           "# directed three share their boundaries, and so do rne and rmm.",
           "# fp32 has none: at G = 40 its windows are empty. exp2 has none.",
           ""]
    names = {}
    for fn, per_fmt in data.items():
        for fmt_name, per in per_fmt.items():
            for lst in per.values():
                key = (fn, fmt_name, tuple(lst))
                if key in names:
                    continue
                names[key] = f"_{fn.upper()}_{fmt_name.upper()}_{len(names) + 1}"
                if not lst:
                    out.append(f"{names[key]} = []")
                    continue
                lines, line = [], "    "
                for centre in lst:
                    tok = _token(centre)
                    if len(line) + len(tok) + 1 > 78:
                        lines.append(line.rstrip())
                        line = "    "
                    line += tok + " "
                lines.append(line.rstrip())
                out.append(f"{names[key]} = [" + NL + NL.join(lines) + NL
                           + "]")
    out += ["", "FAMILY = {"]
    for fn, per_fmt in data.items():
        out.append(f'    "{fn}": {{')
        for fmt_name, per in per_fmt.items():
            out.append(f'        "{fmt_name}": {{')
            for rnd_name, lst in per.items():
                ref = names[(fn, fmt_name, tuple(lst))]
                out.append(f'            "{rnd_name}": {ref},')
            out.append("        },")
        out.append("    },")
    out.append("}")
    return NL.join(out) + NL


def write(path=None):
    """Regenerate FAMILY into this file (everything from the marker line)."""
    path = Path(path or __file__)
    text = path.read_text(encoding="utf-8")
    head = text[:text.index(_MARKER)]
    path.write_text(head + render(generate()), encoding="utf-8", newline=NL)


