# THE THRESHOLDS: B is the budget's largest cell for the function and format
# over its regions, the larger of the study's figure for the cell (docs/studies
# /m3/budget.*.out.txt and box-sb1/, bound + residual) and this tool's
# (mathlib_pow_budget at the desktop's sizes, `pow-budget`), rounded UP to two
# figures. A lane MUST be marked when d < 1 - B, MUST NOT when d > 1 + B,
# between either. THEY ARE ONLY AS GOOD AS THE BUDGET'S BOUND OVER ITS SAMPLE
# (a sampled figure, not a bound over all lanes): the reference leg holds the
# tool to the model's digits (19 cells) and `pow-budget` checks every cell's
# figure against its B (a cell past it is a finding of `pow-budget`, not a
# number to loosen).
THRESHOLD_B = {
    ("pow", "fp64"): 0.19, ("powr", "fp64"): 0.12, ("pown", "fp64"): 0.16,
    ("rootn", "fp64"): 0.030, ("compound", "fp64"): 0.38,
    ("pow", "fp128"): 0.0037, ("powr", "fp128"): 0.0014,
    ("pown", "fp128"): 0.0034, ("rootn", "fp128"): 0.00056,
    ("compound", "fp128"): 0.0034,
    ("pow", "fp256"): 0.0067, ("powr", "fp256"): 0.0031,
    ("pown", "fp256"): 0.0072, ("rootn", "fp256"): 0.0025,
    ("compound", "fp256"): 0.0073,
}


def thresholds(fmt, fn):
    """(must, clear) for the function and format: 1 - B and 1 + B."""
    B = THRESHOLD_B[(fn, fmt.name)]
    return round(1 - B, 6), round(1 + B, 6)


def cls_of(rnd):
    return "nearest" if rnd in NEAREST else "directed"


def rep_of(cls):
    """The attribute that stands for a class in the theory."""
    return sf.RND_RNE if cls == "nearest" else sf.RND_RTZ


# ---- encodings -------------------------------------------------------------------

def _val(fmt, sign, m, e):
    """(-1)^sign m 2^e as an encoding, or None where it is not exact."""
    bits, fl = sf.round_pack(fmt, sign, m, e, sf.RND_RNE)
    return None if fl else bits


def _q(fmt, q):
    return ml._enc(fmt, Fraction(q))


def _mp(q):
    return mpmath.mpf(q.numerator) / q.denominator


# ---- golden's classes, the in-lane rule's domain ----------------------------------

@functools.lru_cache(maxsize=None)
def golden_class(fmt, fn, lane):
    """rep, mid, exo, irr or range by transcend.py's OWN exactness tests: the
    exact value (an odd part and an exponent) of the lane where golden has one:
    rep representable, mid an odd part of p + 1 bits (a midpoint of two
    floats), exo an exact value past it, irr where golden has none (it is
    irrational, not dyadic, or too wide), range a value past the format."""
    x, b2 = lane
    ux = sf.unpack(fmt, x)
    p = fmt.prec
    try:
        if fn in ("pow", "powr"):
            ex = tr._pow_dyadic(fmt, ux, sf.unpack(fmt, b2))
        elif fn == "pown":
            ex = tr._pown_dyadic(fmt, ux.m, ux.e, b2)
        elif fn == "rootn":
            ex = tr._rootn_dyadic(fmt, ux, b2)
        else:
            sm, se = tr._exact_one_plus(ux)
            ex = tr._pown_dyadic(fmt, sm, se, b2)
    except Exception:                                  # noqa: BLE001
        return "irr"
    if ex is None:
        return "irr"
    m, e = ex
    if m == 0:
        return "irr"
    low = (m & -m).bit_length() - 1
    odd, e2 = m >> low, e + low
    vexp = e2 + odd.bit_length() - 1
    if vexp > fmt.emax or vexp < fmt.emin - fmt.man_w - 1:
        return "range"
    if odd.bit_length() <= p and e2 >= fmt.emin - fmt.man_w:
        return "rep"
    if odd.bit_length() == p + 1 or e2 == fmt.emin - fmt.man_w - 1:
        return "mid"
    return "exo"


@functools.lru_cache(maxsize=None)
def power_base(fmt, fn, lane):
    """The lane's base (|x|, or |1 + x| exactly for compound) is a power of
    two: the in-lane rule's domain (ex: rp = 0, t_l = 0, r = 0)."""
    q = abs(P.value(fmt, lane[0]) + (1 if fn == "compound" else 0))
    return q > 0 and not q.numerator & (q.numerator - 1) \
        and not q.denominator & (q.denominator - 1)


@functools.lru_cache(maxsize=None)
def gated_why(fmt, fn, lane):
    """None, or why the lane is never marked: a special row (the harness's
    in_main says the main path does not answer it) or a result past the
    screens (|f| at least 2^(emax+1) or under 2^(emin-p-2))."""
    ok = (P.in_main_n if fn in INT_FUNCS else P.in_main)(fn, fmt, lane)
    if not ok:
        return "special"
    with mpmath.workprec(4 * fmt.prec + 200):
        T = abs(P.true_value(fn, fmt, lane))
        if T == 0 or mpmath.isinf(T):
            return "range"
        e = mpmath.mag(T) - 1
    if e >= fmt.emax + 2 or e < fmt.emin - fmt.prec - 2:
        return "range"      # the screens: t_h at or past emax + 2 or emin - p - 2
    r = _gate_ratio(fmt, fn, lane)
    if r is not None and r < 1 - 1e-6:
        return "near1"
    return None


@functools.lru_cache(maxsize=None)
def _gate_ratio(fmt, fn, lane):
    """|t| / 2^-(p+3), t = Y log2 |X| (the exponent of the result): the beside-1
    gate decides a lane (the in-lane rule, never marked) where it is under 1.
    None where X = 1 exactly (a special row)."""
    x, y = lane
    X = abs(P.value(fmt, x) + (1 if fn == "compound" else 0))
    if X == 1 or X == 0:
        return None
    with mpmath.workprec(fmt.prec + 64):
        L = abs(mpmath.log(_mp(X), 2))
        Y = abs(_mp(P.value(fmt, y))) if fn in ("pow", "powr") else (
            1 / mpmath.mpf(abs(y)) if fn == "rootn" else mpmath.mpf(abs(y)))
        return float(L * Y * mpmath.mpf(2) ** (fmt.prec + 3))


# ---- the distance, in units of the lane's own bound ---------------------------------

@functools.lru_cache(maxsize=None)
def _plan_coeffs(fmt_name):
    """(B1 / BREL, B2 / BREL): the plan's coefficients in units of the
    nominal bound's 2^-(p+G): 1/8 and 1/16 at fp64, 0 where the plan has none
    (fp128, fp256)."""
    fmt = P.BY_NAME[fmt_name]
    pl = ml.plan_pow(fmt)
    rel = Fraction(1, 2 ** (fmt.prec + pl.G))
    return float(pl.B1 / rel), float(pl.B2 / rel)


@functools.lru_cache(maxsize=None)
def bound_factor(fmt, fn, lane):
    """(lo, hi): Bv / (2^-(p+G) |V|) on the lane by the theory, 1 + |t| b1 +
    |Y k| b2 with b1, b2 the plan's coefficients in nominal units
    (_plan_coeffs), t = Y log2 |X| (X = |x|, or |1 + x| for compound), k the
    reduction's exponent: floor(log2 |X|), or one more where the mantissa is
    at or past 241/128 (the reduction's boundary); both are tried where the
    lane is within 2^-20 of it, and each factor is taken a part in a million
    on its side. (1, 1) where the plan has no B."""
    b1, b2 = _plan_coeffs(fmt.name)
    if not b1 and not b2:
        return 1.0, 1.0
    p = fmt.prec
    x, y = lane
    X = abs(P.value(fmt, x) + (1 if fn == "compound" else 0))
    with mpmath.workprec(p + 64):
        L = mpmath.log(_mp(X), 2)
        Y = abs(float(P.value(fmt, y))) if fn in ("pow", "powr") else (
            1.0 / abs(y) if fn == "rootn" else float(abs(y)))
        t = abs(float(L)) * Y
        E = int(mpmath.floor(L))
        m = float(X / Fraction(2) ** E)
    ks = {E if m < 241 / 128 else E + 1}
    if abs(m - 241 / 128) < 2.0 ** -20:
        ks = {E, E + 1}
    fs = [1 + b1 * t + b2 * Y * abs(k) for k in ks]
    return min(fs) * (1 - 1e-6), max(fs) * (1 + 1e-6)


@functools.lru_cache(maxsize=None)
def distances(fmt, fn, lane):
    """(midpoint, grid): the distance from |f| to the nearest midpoint of two
    floats and to the nearest float, each relative to |f| and in units of the
    nominal 2^-(p+G), by mpmath at 4p + 200 bits. The in-lane test runs in the
    SCALED domain, whose cell is p bits wide at |f|'s own binade, so for a
    result under 2^emin (the subnormal grid, whose cell is wider) the
    boundaries are the union of that cell's and the fixed grid's: the nearer
    of the two is taken. Cached: the attributes share it."""
    p, G = fmt.prec, ml.GUARD[fmt.name]
    with mpmath.workprec(4 * p + 200):
        T = abs(P.true_value(fn, fmt, lane))
        e0 = mpmath.mag(T) - 1
        unit = mpmath.mpf(2) ** (-(p + G))
        best = [None, None]
        for e in sorted({e0, max(e0, fmt.emin)}):
            ulp = mpmath.mpf(2) ** (e - p + 1)
            q = T / ulp
            frac = q - mpmath.floor(q)
            m = float(abs(frac - mpmath.mpf(1) / 2) * ulp / T / unit)
            g = float(min(frac, 1 - frac) * ulp / T / unit)
            best = [m if best[0] is None else min(best[0], m),
                    g if best[1] is None else min(best[1], g)]
        return tuple(best)


def distance(fmt, rnd, fn, lane):
    """d in nominal units: the distance to the nearest boundary of the
    attribute's class."""
    mid, grid = distances(fmt, fn, lane)
    # rne and rmm: the boundaries are the midpoints AND the floats (the "may
    # be exact" test marks a V within the bound of a float, which is why the
    # test's law has spacing ulp/2 there); the directed three: the floats
    return min(mid, grid) if rnd in NEAREST else grid


def status(fmt, rnd, fn, lane):
    """"must", "clear", "either", "decided" or "gated": what the theory demands
    of the routine on the lane under the attribute (the module docstring)."""
    if gated_why(fmt, fn, lane):
        return "gated"
    cls = golden_class(fmt, fn, lane)
    if cls == "range":
        return "gated"
    if cls in ("rep", "mid") and power_base(fmt, fn, lane):
        return "decided"             # exact, base 2^E: the in-lane rule
    if cls == "rep" or (cls == "mid" and rnd in NEAREST):
        # an exact lane that is a rounding boundary of the attribute: golden's
        # d is 0; the in-lane rule decides it where the base is a power of two
        return "decided" if power_base(fmt, fn, lane) else "must"
    r = _gate_ratio(fmt, fn, lane)
    if r is not None and abs(r - 1) <= 1e-6:
        return "either"                 # on the gate's own edge
    with mpmath.workprec(4 * fmt.prec + 200):
        if mpmath.mag(abs(P.true_value(fn, fmt, lane))) - 1 >= fmt.emax + 1:
            return "either"             # past the format, under the screen
    must, clear = thresholds(fmt, fn)
    d = distance(fmt, rnd, fn, lane)
    lo, hi = bound_factor(fmt, fn, lane)
    return "must" if d / lo < must else "clear" if d / hi > clear else "either"


def predicted(fmt, rnd, fn, lane):
    """Whether the theory allows the lane to be marked."""
    return status(fmt, rnd, fn, lane) in ("must", "either")


# ---- the generators ---------------------------------------------------------------

INTPOW_MS = (3, 5, 7)
ROOT_RS = (3, 5, 7)
DOM_NS = (2, 3, 5, -1, -2)
DOM_MS = (1, 3, 5, 7)


def _ymax(p, M):
    return (p + 1) // M.bit_length() + 2


def _ys(p, M, keyed):
    """The integers y (or n) of M's family: 2 to (p + 1) / bits(M) + 4 for
    pow and powr; for the n-keyed three, whose n is a fragment of its own, 2,
    3 and the five around the end of the exact range (M^n of p - 1 to p + 3
    bits: where rep turns to mid and to nothing)."""
    top = _ymax(p, M) + 2
    if not keyed:
        return range(2, top + 1)
    return sorted({2, 3} | set(range(top - 4, top + 1)))


def gen_intpow(fmt, fn):
    p, out = fmt.prec, []
    if fn == "rootn":
        return out
    for M in INTPOW_MS:
        for y in _ys(p, M, fn in INT_FUNCS):
            if fn in ("pow", "powr"):
                for sg in ((0, 1) if fn == "pow" else (0,)):
                    out.append((_val(fmt, sg, M, 0), _val(fmt, 0, y, 0)))
            elif fn == "pown":
                for sg in (0, 1):
                    out.append((_val(fmt, sg, M, 0), y))
            else:
                out.append((_q(fmt, M - 1), y))
    return out


def gen_root2k(fmt, fn):
    p, out = fmt.prec, []
    if fn in ("pow", "powr"):
        for k in (1, 2, 3):
            for R in ROOT_RS:
                for e in (0, -1):
                    x = _val(fmt, 0, R ** (2 ** k), e * 2 ** k)
                    for Y in (1, 3, 5, 7):
                        for sg in (0, 1):
                            out.append((x, _val(fmt, sg, Y, -k)))
    elif fn == "rootn":
        for n in SMALL_NS:
            for R in (3, 5, 7, 9, 11, 13, 15):
                if (R ** abs(n)).bit_length() > p:
                    continue
                for e in (0, -2):
                    for sg in ((0, 1) if n % 2 else (0,)):
                        out.append((_val(fmt, sg, R ** abs(n), e * abs(n)),
                                    n))
    return [(x, y) for x, y in out if x is not None and y is not None]


def _pow2_es(fmt):
    lo, hi = fmt.emin - fmt.prec + 1, fmt.emax
    es = {lo + (hi - lo) * i // 8 for i in range(9)}
    es |= {-3, -1, 1, 2, 3, 10, lo, hi}
    return sorted(e for e in es if lo <= e <= hi)


def gen_pow2(fmt, fn):
    p, out = fmt.prec, []
    es = _pow2_es(fmt)
    if fn in ("pow", "powr"):
        ys = [_val(fmt, 0, 2, 0), _val(fmt, 0, 3, 0), _val(fmt, 1, 1, 0),
              _val(fmt, 1, 2, 0), _val(fmt, 0, 7, 0)]
        ys += [_val(fmt, s, m, -k) for s, m, k in ((0, 1, 1), (1, 1, 1),
                                                  (0, 3, 1), (1, 1, 2))]
        ys += [_val(fmt, 0, (1 << (p - 1)) | 1, -(p - 1)),
               _val(fmt, 1, (1 << (p - 1)) | 5, -(p + 3))]
        for e in es:
            for sg in ((0, 1) if fn == "pow" else (0,)):
                for y in ys:
                    out.append((_val(fmt, sg, 1, e), y))
    elif fn in ("pown", "rootn"):
        for e in es[::2]:
            for n in (FAMILY_NS if fn == "pown" else (2, 3, -2, -3)):
                for sg in ((0, 1) if n % 2 else (0,)):
                    out.append((_val(fmt, sg, 1, e), n))
    else:
        for e in (1, 2, 3, 8, p - 1, p, -1, -2, -3, -8):
            q = Fraction(2) ** e - 1
            for n in (2, 3, -2, -3, 17):
                out.append((_q(fmt, q), n))
    return [(x, y) for x, y in out if x is not None and y is not None]


def gen_near1(fmt, fn):
    if fn not in ("pow", "powr"):
        return []
    one, out = sf.one_bits(fmt), []
    for k in range(1, 9):
        for x in (one + k, one - k):
            for sh in (-2, 0, 2):
                for f in (Fraction(0), Fraction(1, 2)):
                    y = _q(fmt, Fraction(2) ** (-4 + sh) / k * (1 + f))
                    out += [(x, y), (x, y | fmt.sign_mask)]
    return out


def gen_dominant(fmt, fn):
    if fn != "compound":
        return []
    p, G, out = fmt.prec, ml.GUARD[fmt.name], []
    for n in DOM_NS:
        b = abs(n).bit_length()
        for M in DOM_MS:
            for e in (p + 1 + b, p + 2 + b, p + 3 + b, p + G + b - 1,
                      p + G + b, p + G + b + 1):
                if e * abs(n) >= fmt.emax - 2:
                    continue
                x = _val(fmt, 0, M, e)
                if x is not None:
                    out.append((x, n))
    return out


def gen_edges(fmt, fn):
    if fn not in ("pow", "powr"):
        return []
    p, out = fmt.prec, []
    hi = [(2, "high", c) for c in (Fraction(1, 2), Fraction(1), Fraction(3, 2))]
    lo = [(1, "low", c) for c in (Fraction(1, 2), Fraction(1), Fraction(3, 2),
                                  Fraction(2), Fraction(3))]
    with mpmath.workprec(4 * p):
        for j in range(4):
            for s in (1, 2, 3):
                x = _val(fmt, 0, (1 << (p - 1)) + j, -p + 1 + s)
                X = _mp(P.value(fmt, x))
                for _t, kind, c in hi + lo:
                    if kind == "high":
                        tgt = mpmath.mpf(2) ** fmt.emax * (
                            2 - mpmath.mpf(2) ** (1 - p) * _mp(c))
                    else:
                        tgt = mpmath.mpf(2) ** (fmt.emin - fmt.man_w) * _mp(c)
                    out.append((x, _q(fmt, ml._frac(mpmath.log(tgt)
                                                    / mpmath.log(X)))))
    return out


def gen_smallint(fmt, fn):
    p, out = fmt.prec, []
    if fn == "pown":
        for n in SMALL_NS:
            for M in (1, 3, 5, 7, 9, 15):
                for e in (-2, 0, 3):
                    for sg in ((0, 1) if n % 2 else (0,)):
                        out.append((_val(fmt, sg, M, e), n))
    elif fn == "rootn":
        for n in SMALL_NS:
            for M in (1, 3, 5, 7, 9):
                for e in (-1, 0, 2):
                    pf = M ** abs(n)
                    for x in (_val(fmt, 0, pf, e * abs(n)),
                              _val(fmt, 0, M, e)):
                        out.append((x, n))
    elif fn == "compound":
        for n in SMALL_NS:
            for M in (1, 3, 5, 7, 9, 15):
                for e in (-2, 0, 3):
                    out.append((_q(fmt, Fraction(M) * Fraction(2) ** e - 1),
                                n))
    return [(x, y) for x, y in out if x is not None and y is not None]


def gen_hard3p(fmt, fn):
    if fn not in ("pow", "powr"):
        return []
    one, out = sf.one_bits(fmt), []
    for k in range(1, 5):
        for j in range(0, 5):
            for xs in (one + k, one - k):
                for ys in (one + j, one - j if j else None):
                    if ys is None:
                        continue
                    for sg in (0, fmt.sign_mask):
                        out.append((xs, ys | sg))
    return out


def gen_twop(fmt, fn):
    p, one, out = fmt.prec, sf.one_bits(fmt), []
    if fn == "pown":
        for k in range(1, 5):
            for x in (one + k, one - k):
                out += [(x, n) for n in (2, 3, -1, -2, -3)]
        for e in (-5, 0, 7):
            for dx in (1, -1):
                out.append((_val(fmt, 0, 1, e) + dx, -1))
    elif fn == "compound":
        for k in range(1, 5):
            for x in (_q(fmt, Fraction(k, 2 ** (p - 1))),
                      _q(fmt, -Fraction(k, 2 ** p))):
                out += [(x, n) for n in (2, 3, -1, -2, -3)]
    elif fn == "rootn":
        for j in range(-3, 4):
            out.append((_val(fmt, 0, (1 << (p - 1)) + 1, 2 * j - (p - 1)), 2))
    else:
        mx = sf.max_normal_bits(fmt)
        out += [(mx, _val(fmt, 1, 1, 0))]
    return [(x, y) for x, y in out if x is not None and y is not None]


def gen_tie(fmt, fn):
    """The tie at half the least subnormal, where the function has it: pown(2,
    emin - p) and compound(1, emin - p): 2^(emin - p) is the midpoint of 0 and
    the least subnormal."""
    n = fmt.emin - fmt.prec
    if fn == "pown":
        return [(_val(fmt, 0, 1, 1), n)]
    if fn == "compound":
        return [(sf.one_bits(fmt), n)]
    return []


