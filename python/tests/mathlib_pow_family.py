"""The structured families of pow, powr, pown, rootn and compound (parcel M3G3):
the arguments whose true value is exact, or within the in-lane bound of a
rounding boundary, which the test marks and a replay decides (docs/studies/
M3-pow.md, 3.5, 8 items 4 to 6; Logan's answers of 2026-11-19: the exact family
is decided in the lane only where cheap and exact, every other exact case is
marked and replayed, and "a mark off the list fails"). mathlib_inv_family.py's
design, for two inputs and the integer operand.

THE THEORY, independent of the fragment (status()). A lane is, for an
attribute (its class: the nearest two, rne and rmm, mark where a midpoint is
within the bound, the directed three where a float is):

  gated     never marked: a special row (a NaN, an infinity, a zero, x or y =
            1, n = 0 or 1, a negative x with a non-integer y, powr's negative
            x, compound's x <= -1, pown's and rootn's |x| = 1) or a result
            past the screens' reach (|f| at least 2^(emax+1) or under
            2^(emin-p-2));
  decided   an EXACT lane of golden's own rule (transcend._pow_dyadic,
            _pown_dyadic, _rootn_dyadic, and _exact_one_plus with _pown_dyadic
            for compound: an exact value that is representable (rep), or a
            midpoint (mid) under rne and rmm) whose BASE is a power of two
            (x = +-2^E, or 1 + x = 2^E for compound): the in-lane rule (ex:
            rp = 0, t_l = 0, r = 0, and u_l = 0 for compound) decides it, it
            is never marked and is right in bits and flags;
  must      every other exact boundary lane (rep under all five attributes,
            mid under rne and rmm: golden's d is 0 by its rule, not by
            mpmath) MUST mark, and an irrational lane whose distance d from
            the nearest boundary (mpmath at 4p + 200 bits) is under 1 - B;
  clear     d over 1 + B: must NOT mark, and is right unmarked (this takes the
            exact lanes that are no boundary under the attribute: a midpoint
            under the directed three, an exact value past p + 1 bits);
  either    between: if marked, its guess is counted, not judged.

d is in units of THE LANE'S OWN BOUND Bv, not of the nominal 2^-(p+G) |f|: at
fp64 Bv = |V| (2^-(p+G) + |t| B1 + |Y k| B2) with B1 = 2^-100 and B2 = 2^-101
(the plan's), up to 135 times the nominal, so a lane at 5 nominal bounds from a
boundary is inside its own and marks. The factor is computed from the lane's t
and k by the theory (bound_factor); at fp128 and fp256 (B1 = B2 = 0) it is 1.
B is THRESHOLD_B's: the budget's largest cell for the function and format (the
study's figures and mathlib_pow_budget's, the larger, rounded up to two
figures), so that 1 - B and 1 + B hold wherever the budget's bound does: the
budget bounds |V - f| / Bv by B, so a lane farther than (1 + B) Bv from a
boundary cannot be within Bv of it, and one nearer than (1 - B) Bv is within
Bv.

THE FAMILIES (generators, from their definitions, not drawn): intpow (x = +-M,
M odd short, y or n an integer from 2 to (p + 1) / bits(M) + 4), root2k (y =
+-Y / 2^k, x a perfect 2^k-th power; rootn's perfect |n|-th powers), pow2 (x
= +-2^E over the whole range, y an integer, a short dyadic or a p-bit value;
pown, rootn; compound's 1 + x = 2^E), near1 (x = 1 +- k ulp, y about golden's
2^-(p+3) threshold), dominant (compound(x, n), x = M 2^e at golden's
threshold e = p + 2 + bits(|n|) (transcend.py:2761) and beside it, and at the
routine's own where the correction (1 + 1/x)^n falls under 2^-(p+G)), edges
(x^y within half an ulp to 2 ulps of the largest finite or of the subnormal
grid's least points), smallint (pown, rootn, compound at n = +-2, +-3 on short
odd parts), hard3p (x = 1 +- k u, y = +-(1 +- j u)), twop (the 2p family of the
pools' marks: (1 +- k u)^n, sqrt(4^j (1 + u)), 1/x one ulp from a power of two,
pow(max, -1)), and tie (pown(2, emin - p) and compound(1, emin - p): the tie at
half the least subnormal).

THE COMMITTED LIST (POW_FAMILY, at the end of this file) is POW_FAMILY[fn][fmt]
[attribute] = [entry, ...], an entry (family, lanes, must, clear, either,
decided, gated, digest): how many lanes of the family the theory generates for
fn at fmt, what it demands of each under that attribute's class, and a digest
of the lane list itself. GENERATED by
generate() from the theory alone and held to a fresh generation by
test_mathlib_pow_family.py and by `pow-family --check`, so it can neither go
stale nor be edited by hand to agree with a fault. The literal is written by
`pow-family --write` as two classes a function and format (nearest, directed:
rtz, rdn and rup are one class, rne and rmm the other) and POW_FAMILY expands
them by attribute.

    python python/tests/mathlib_runs.py pow-family --write    regenerate
"""

