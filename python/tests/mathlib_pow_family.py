def census_lanes(fmt, name, count, seed=1):
    """[(fn, lane)]: docs/studies/m3/census.py's family(), ported with the
    SAME draws (random.Random(seed * 7919 + width), the same calls in the
    same order), so that its lanes are the study's."""
    rng = random.Random(seed * 7919 + fmt.width)
    p = fmt.prec
    out = []
    one = sf.one_bits(fmt)
    if name == "intpow":
        for _ in range(count):
            mb = rng.randint(1, max(2, p // 3))
            M_ = rng.getrandbits(mb) | 1
            E = rng.randint(-8, 8)
            nmax = max(2, (p + 1) // max(1, M_.bit_length()))
            n = rng.randint(2, nmax + 2)
            x = _val(fmt, rng.random() < 0.3, M_, E)
            y = _val(fmt, rng.random() < 0.1, n, 0)
            if x is None or y is None:
                continue
            out.append(("pow", (x, y)))
    elif name == "root2k":
        for _ in range(count):
            k = rng.randint(1, 3)
            R = rng.getrandbits(rng.randint(1, max(2, p // (2 ** k)))) | 1
            Mx = R ** (2 ** k)
            if Mx.bit_length() > p:
                continue
            E = rng.randint(-4, 4) * 2 ** k
            Y = rng.getrandbits(rng.randint(1, 6)) | 1
            x = _val(fmt, 0, Mx, E)
            y = _val(fmt, rng.random() < 0.2, Y, -k)
            if x is None or y is None:
                continue
            out.append(("pow", (x, y)))
    elif name == "pow2":
        for _ in range(count):
            E = rng.randint(fmt.emin - p + 1, fmt.emax)
            x = _val(fmt, rng.random() < 0.2, 1, E)
            kind = rng.random()
            if kind < 0.4 and E:
                lim = max(1, (fmt.emax + p) // abs(E))
                y = _val(fmt, rng.random() < 0.5, rng.randint(1, lim + 2), 0)
            elif kind < 0.7:
                y = _val(fmt, rng.random() < 0.5,
                         rng.getrandbits(5) | 1, -rng.randint(1, 4))
            else:
                y = _val(fmt, rng.random() < 0.5,
                         rng.getrandbits(p) | (1 << (p - 1)),
                         -p - rng.randint(-4, 12))
            if x is None or y is None:
                continue
            out.append(("pow", (x, y)))
    elif name == "near1":
        for _ in range(count):
            k = rng.randint(1, 8)
            x = one + k if rng.random() < 0.5 else one - k
            sh = rng.uniform(-3, 3)
            y = ml._enc(fmt, Fraction(2) ** int(-4 + sh) / k
                        * (1 + Fraction(rng.getrandbits(20), 1 << 21)))
            if rng.random() < 0.5:
                y |= fmt.sign_mask
            out.append(("pow", (x, y)))
            out.append(("powr", (x, y)))
    elif name == "dominant":
        for _ in range(count):
            n = rng.choice((1, 2, 3, -1, -2, 5))
            if n == 1:
                n = 2
            e = rng.randint(p + 2 + abs(n).bit_length(),
                            max(p + 3 + abs(n).bit_length(),
                                fmt.emax // max(1, abs(n))))
            M_ = rng.choice((1, 3, 5, 7))
            x = _val(fmt, 0, M_, e)
            if x is None:
                continue
            out.append(("compound", (x, n)))
    elif name == "edges":
        for _ in range(count):
            x = _val(fmt, 0, rng.getrandbits(p - 1) | (1 << (p - 1)),
                     -p + 1 + rng.randint(1, 6))
            with mpmath.workprec(4 * p):
                X = _mp(P.value(fmt, x))
                if rng.random() < 0.5:
                    tgt = mpmath.mpf(2) ** fmt.emax * (
                        2 - mpmath.mpf(2) ** (1 - p)
                        * rng.choice((0.5, 1, 1.5)))
                else:
                    tgt = mpmath.mpf(2) ** (fmt.emin - fmt.man_w) * \
                        rng.choice((0.5, 1, 1.5, 2, 3))
                yv = mpmath.log(tgt) / mpmath.log(X)
                y = ml._enc(fmt, ml._frac(yv))
            out.append(("pow", (x, y)))
    elif name == "hard3p":
        u = 1
        for k in range(1, 9):
            for j in range(0, 9):
                for xs in (one + k * u, one - k * u):
                    for ys in (one + j * u, one - j * u if j else None):
                        if ys is None:
                            continue
                        for sg in (0, fmt.sign_mask):
                            out.append(("pow", (xs, ys | sg)))
        out = out[:count] if count < len(out) else out
    elif name == "smallint":
        for _ in range(count):
            fn = rng.choice(("pown", "rootn", "compound"))
            n = rng.choice((2, 3, -2, -3))
            mb = rng.randint(1, max(2, p // 3))
            M_ = rng.getrandbits(mb) | 1
            if fn == "rootn":
                M_ = M_ ** abs(n) if (M_ ** abs(n)).bit_length() <= p else M_
                E = rng.randint(-6, 6) * abs(n)
            else:
                E = rng.randint(-6, 6)
            x = _val(fmt, fn != "compound" and rng.random() < 0.3 and
                     (fn != "rootn" or n % 2), M_, E)
            if x is None:
                continue
            out.append((fn, (x, n)))
    else:
        raise ValueError(name)
    return out


def census_run(fmt, name, count, rnds=sf.RND_MODES, seed=1, items=None):
    """{rnd: {class: (lanes, marked, guess_wrong, wrong, off_rule)}} of the
    study's census family `name` through the fragments (golden's own classes,
    docs/studies/m3/census.py's counts: lanes, marked, marked with a guess
    that differs from golden's in bits or flags, unmarked and wrong, the exact
    representable lanes decided unmarked whose base (x, or 1 + x) is no power
    of two and which are outside the rule's other domains (off_rule), and the
    marks the theory does not predict (off the list)), and the class counts."""
    items = census_lanes(fmt, name, count, seed) if items is None else items
    cls = {}
    for fn, lane in items:
        cls.setdefault(golden_class(fmt, fn, lane), []).append((fn, lane))
    counts = {k: len(v) for k, v in cls.items()}
    res = {}
    for rnd in rnds:
        row = {}
        for k, its in sorted(cls.items()):
            marked = gw = wrong = off = offl = 0
            for fn, lane in its:
                bits, fw = runner(fmt, fn, rnd)(lane)
                gb, gf = P.golden(fmt, rnd, lane, fn)
                if fw & MARK:
                    marked += 1
                    gw += (bits, fw & ~MARK) != (gb, gf)
                    offl += not predicted(fmt, rnd, fn, lane)
                elif (bits, fw) != (gb, gf):
                    wrong += 1
                elif k == "rep" and not power_base(fmt, fn, lane) \
                        and (fn in INT_FUNCS or not _y_is_one(fmt, lane)):
                    off += 1
            row[k] = (len(its), marked, gw, wrong, off, offl)
        res[rnd] = row
    return counts, res


def _y_is_one(fmt, lane):
    """y = 1 or -1 (the rule's other domain: x itself is the answer)."""
    return abs(P.value(fmt, lane[1])) == 1


