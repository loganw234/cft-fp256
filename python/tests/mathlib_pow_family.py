def render(data):
    """The literal's text for `data` ({fn: {fmt: {class: [entry]}}}): one
    entry a line."""
    lines = ["_FAMILY_CLASSES = {"]
    for fn in FUNCTIONS:
        lines.append(f"    {fn!r}: {{")
        for fm, cs in data[fn].items():
            lines.append(f"        {fm!r}: {{")
            for c in CLASSES:
                lines.append(f"            {c!r}: [")
                lines += [f"                {tuple(e)!r}," for e in cs[c]]
                lines.append("            ],")
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    lines.append("POW_FAMILY = expand_classes(_FAMILY_CLASSES)")
    return "\n".join(lines) + "\n"


def write(path=None, data=None):
    """Rewrite the committed list at the end of this file from the theory
    (or from `data`)."""
    path = Path(path or __file__)
    text = path.read_bytes().decode("utf-8")
    head = text[:text.index(_MARKER + "\n") + len(_MARKER) + 1]
    path.write_bytes((head + render(data or generate())).encode("utf-8"))


