"""The library's own sources as one GPU translation unit: the few lines a
device build compiles in their place, generated here and checked whole.

    python3 tools/hip_unit.py unit DIR     DIR/cft_hip_unit.hip (host/Makefile's HIP=1 check)
    python3 tools/hip_unit.py gpua DIR     GPU-A's harnesses against the tree (below)
    python3 tools/hip_unit.py check DIR    every file this script writes there, compared again
    python3 tools/hip_unit.py selftest     the plants, each of which `check` must refuse

NOT A COPY. HIP and CUDA compile a function for a GPU when it carries
__device__, and bigint, softfloat and the sequencer's executor carry
CFT_HD (cft_config.h), so the tree's text compiles for a GPU as it is.
Study GPU-A compiled a COPY of host/src instead, edited at every build by
docs/studies/gpu-a/devcopy.py. Nothing written here is a copy of
anything: each file is an #include of the tree's own file by its
absolute path, with at most the macros its includer needs. The text of
each is fixed in this script, written, read back and compared byte for
byte, so a file in DIR that is not exactly this script's is refused by
name - by `check`, and by every build that writes one.

unit - one translation unit of the tree's bigint.c, softfloat.c and
seq_exec.h, as the GPU backend's kernels will be one (no relocatable
device code, nothing linked across units). BLOCK_LANES is 1, a thread a
lane. CFT_NO_AUGMENTED, because augmented.c does not compile for an
NVIDIA device as it is (docs/VALIDATION.md, G1A). Two kernels, never
launched, reach the arithmetic and the executor's per-lane functions:
a device compiler generates no code for a static function nothing
calls, and a check that compiled none would pass whatever it held.

gpua - in place of devcopy.py's devsrc/: src/bigint.c, src/softfloat.c,
src/seqcore.c (BLOCK_LANES 1, and CFT_SEQ_ALU as the runner's hook
CFT_GPUA_ALU), include/cft.h and sha/sha256.h. Then
docs/studies/gpu-a/cft_fma.hip and cft_seq.hip, unchanged, build against
the tree with build.sh's and build_seq.sh's own compile lines and
-I DIR -I DIR/include -I DIR/sha in place of the copy's.
"""
import argparse
import shutil
import sys
import tempfile
from pathlib import Path

HOST = Path(__file__).resolve().parents[1]
UNIT = "cft_hip_unit.hip"
STAMP = ("/* GENERATED by host/tools/hip_unit.py ({kind}) and checked whole by\n"
         " * it: not a copy - the tree's own file, included. */\n")


def tree(rel):
    """An #include line for a file of the tree, by absolute path."""
    p = (HOST / rel).resolve()
    s = p.as_posix()
    if not p.is_file():
        raise ValueError(f"{rel}: not a file at {s}")
    if '"' in s or "\n" in s:
        raise ValueError(f"{rel}: a path an #include cannot spell: {s!r}")
    return f'#include "{s}"\n'


def unit_text():
    # hip_runtime.h first, as in any HIP source: the kernels' blockIdx and
    # threadIdx, and on AMD the device memset that seq_exec.h's per-lane
    # functions call (nvcc has its own built in)
    return (STAMP.format(kind="unit") +
            "#include <hip/hip_runtime.h>\n"
            "#define CFT_NO_AUGMENTED 1\n"
            "#define BLOCK_LANES 1\n" +
            tree("src/bigint.c") + tree("src/softfloat.c") + tree("src/seq_exec.h") + """
/* The elementwise path: lane i of a batch through cft_sf_compute, as
 * device.c's software loop runs one element. */
__global__ void cft_hip_unit_alu(cft_fmt_desc f, int op, int rnd, const cft_bn *a,
                                 const cft_bn *b, const cft_bn *c, cft_bn *d,
                                 uint32_t *fl, int *rc, size_t n)
{
    const size_t i = (size_t)blockIdx.x * blockDim.x + threadIdx.x;
    if (i < n)
        rc[i] = cft_sf_compute(&f, op, rnd, &a[i], &b[i], &c[i], &d[i], &fl[i]);
}

/* The sequencer's path for lane i, in seq_program_run's order: the
 * deposits, the lane in, seq_run_block on a block of one, the lane out. */
__global__ void cft_hip_unit_seq(cft_program P, cft_fmt_desc f, const cft_bn *konst,
                                 cft_run_args A, cft_bn *scratch, uint32_t *acc)
{
    const size_t i = (size_t)blockIdx.x * blockDim.x + threadIdx.x;
    const size_t esz = (size_t)f.width / 8;
    const uint32_t reach = seq_scratch_reach(&P, P.scratch_depth);
    uint32_t fl = 0, st = 0;
    cft_status rc;
    seq_block B;
    if (i >= A.n)
        return;
    P.f = &f;
    B.depth = P.scratch_depth;
    B.scratch = scratch ? scratch + i * reach : NULL;
    seq_lanes_deposits(&P, &A, i, 1, esz);
    seq_lanes_in(&P, &A, &B, i, 1, esz, reach);
    rc = seq_run_block(&P, konst, &B, 1, (uint8_t *)A.deposits, i, esz, &fl, &st);
    if (rc == CFT_OK)
        seq_lanes_out(&P, &A, &B, i, 1, esz);
    acc[i] = fl | st << 8 | (uint32_t)rc << 16;
}
""")


def gpua_texts():
    return {
        "src/bigint.c": STAMP.format(kind="gpua") + tree("src/bigint.c"),
        "src/softfloat.c": STAMP.format(kind="gpua") + tree("src/softfloat.c"),
        # cft_seq.hip defines CFT_GPUA_ALU (its hook) before it includes
        # this, and a GPU thread is a block of one lane
        "src/seqcore.c": (STAMP.format(kind="gpua") +
                          "#define BLOCK_LANES 1\n"
                          "#define CFT_SEQ_ALU CFT_GPUA_ALU\n" +
                          tree("src/seq_exec.h")),
        "include/cft.h": STAMP.format(kind="gpua") + tree("include/cft.h"),
        "sha/sha256.h": STAMP.format(kind="gpua") + tree("src/sha256.h"),
    }


def texts(kind):
    return {UNIT: unit_text()} if kind == "unit" else gpua_texts()


def check(d, kind):
    """Every file `kind` writes must be in d, exactly this script's text."""
    for rel, want in texts(kind).items():
        p = d / rel
        if not p.is_file():
            raise ValueError(f"{p.as_posix()}: missing")
        got = p.read_bytes()
        if got != want.encode("ascii"):
            gl, wl = got.decode("ascii", "replace").splitlines(), want.splitlines()
            for i, (g, w) in enumerate(zip(gl, wl), 1):
                if g != w:
                    raise ValueError(f"{p.as_posix()}:{i}: not this script's text: {g!r}")
            raise ValueError(f"{p.as_posix()}: {len(gl)} lines, this script's has {len(wl)}")
    return len(texts(kind))


def write(d, kind):
    for rel, text in texts(kind).items():
        p = d / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("ascii"))
    n = check(d, kind)
    print(f"hip_unit: {kind}: {n} files written to {d.as_posix()} and checked whole, "
          f"each an #include of {HOST.as_posix()}'s own file")


def kinds_in(d):
    out = [k for k, probe in (("unit", UNIT), ("gpua", "src/seqcore.c")) if (d / probe).exists()]
    if not out:
        raise ValueError(f"{d.as_posix()}: holds neither kind")
    return out


def selftest():
    bad = 0
    with tempfile.TemporaryDirectory() as tt:
        d = Path(tt)
        t = d.as_posix()
        write(d / "u", "unit")
        write(d / "g", "gpua")
        plants = {
            "a line added to a shim": ("g", "src/bigint.c", lambda s: s + "#define X 1\n"),
            "a shim including another file": ("g", "src/softfloat.c",
                                              lambda s: s.replace("softfloat.c", "bigint.c")),
            "seqcore.c without BLOCK_LANES 1": ("g", "src/seqcore.c",
                                                lambda s: s.replace("#define BLOCK_LANES 1\n", "")),
            "seqcore.c with the ALU hook unset": ("g", "src/seqcore.c",
                                                  lambda s: s.replace("CFT_GPUA_ALU", "cft_sf_compute")),
            "the unit without the sequencer's kernel": ("u", UNIT,
                                                        lambda s: s[:s.index("/* The sequencer")]),
        }
        for what, (sub, rel, f) in plants.items():
            dd = d / ("p-" + sub)
            shutil.copytree(d / sub, dd)
            p = dd / rel
            text = p.read_text()
            planted = f(text)
            assert planted != text, what
            p.write_text(planted)
            try:
                check(dd, "unit" if sub == "u" else "gpua")
                print(f"selftest: plant '{what}' PASSED the check - the check is broken")
                bad += 1
            except ValueError as e:
                print(f"selftest: plant '{what}' refused: {str(e).replace(t, '<tmp>')}")
            shutil.rmtree(dd)
        missing = d / "p-missing"
        shutil.copytree(d / "g", missing)
        (missing / "include/cft.h").unlink()
        try:
            check(missing, "gpua")
            print("selftest: plant 'a shim missing' PASSED the check - the check is broken")
            bad += 1
        except ValueError as e:
            print(f"selftest: plant 'a shim missing' refused: {str(e).replace(t, '<tmp>')}")
        print(f"selftest: honest files: {check(d / 'u', 'unit')} unit, "
              f"{check(d / 'g', 'gpua')} gpua, accepted")
    if bad:
        sys.exit(1)
    print("selftest: OK, 6 plants refused by name")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=("unit", "gpua", "check", "selftest"))
    ap.add_argument("dir", nargs="?", type=Path)
    a = ap.parse_args()
    try:
        if a.what == "selftest":
            selftest()
        elif a.dir is None:
            ap.error("DIR is required")
        elif a.what == "check":
            for k in kinds_in(a.dir):
                print(f"hip_unit: {k}: {check(a.dir, k)} files in {a.dir.as_posix()} "
                      f"are this script's text, whole")
        else:
            write(a.dir, a.what)
    except ValueError as e:
        print(f"hip_unit: REFUSED: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
