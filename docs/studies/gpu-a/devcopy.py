"""GPU-A's device copy of libcft's arithmetic: host/src as it is, plus a
fixed and listed set of edits, checked at every build.

    python3 devcopy.py --root REPO --out BUILD/devsrc     # copy, then check
    python3 devcopy.py --root REPO --out BUILD/devsrc --check-only
    python3 devcopy.py --selftest                         # the plants

The GPU must run libcft's own arithmetic, not a second implementation of
it: a rewrite would need its own proof, and the two would drift. So the
files below are copied from the tree as they are and edited by EDITS and by
nothing else, and the check refuses a copy that differs from its original
by anything else, naming the line. Nothing this writes is committed; it is
regenerated by every build (build.sh).

What had to change, and why (the study, "One source of arithmetic"):

  E1  `CFT_HD ` inserted before every function declaration and definition
      at file scope (a line in column 0 that opens a declarator with one of
      the files' return types). HIP and CUDA compile a function for the
      device only when it carries __device__, and a function that has to
      run on the host as well carries __host__ __device__. The including
      translation unit defines CFT_HD: `__host__ __device__` on a GPU build,
      empty on the CPU build, so the CPU build compiles the original text.
      Declarations get it too, because a redeclaration with another
      execution space is an error in nvcc and an overload in clang.

No other edit was needed: the tables, the C-as-C++ questions, `long`,
`size_t`, shifts and builtins are argued in the study, and the compilers
were the test. If one is ever needed, it is added here as E2 with its
reason, and the check counts it.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

# (source in the tree, path in the copy). cft_config.h is copied unedited:
# bigint.h includes it as "../include/cft_config.h", so the copy keeps the
# tree's layout and that include resolves inside the copy.
FILES = (
    ("host/src/bigint.h", "src/bigint.h"),
    ("host/src/bigint.c", "src/bigint.c"),
    ("host/src/softfloat.h", "src/softfloat.h"),
    ("host/src/softfloat.c", "src/softfloat.c"),
    ("host/include/cft_config.h", "include/cft_config.h"),
)

# E1's pattern: a file-scope function declarator in these files' style.
E1 = re.compile(r"^(static\s+)?(const\s+)?(void|int|unsigned|uint32_t|size_t)"
                r"\s+\**[A-Za-z_][A-Za-z0-9_]*\s*\(")
E1_TEXT = b"CFT_HD "

# Functions E1 must leave alone, by name, each with its reason. Empty: every
# function in the four files compiled for the device on both vendors.
EXCLUDE = {}


def git_blob(data):
    """The git blob id of `data`, so a log names the exact host/src content
    the copy came from without needing git on the build host."""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def e1_applies(line):
    m = E1.match(line.decode("ascii"))
    if not m:
        return False
    name = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(", line.decode("ascii"))
    return name.group(1) not in EXCLUDE


def derive(orig):
    """The copy of one file: E1 on every line it applies to, nothing else."""
    lines = orig.splitlines(keepends=True)
    return b"".join(E1_TEXT + ln if e1_applies(ln) else ln for ln in lines)


def check_one(name, orig, copy):
    """Every difference between `orig` and `copy` must be one E1 insertion on
    a line E1 applies to, and every such line must carry it. Returns the
    number of E1 edits, or raises ValueError naming the first problem."""
    ol = orig.splitlines(keepends=True)
    cl = copy.splitlines(keepends=True)
    if len(ol) != len(cl):
        raise ValueError(f"{name}: {len(cl)} lines in the copy, "
                         f"{len(ol)} in the original (a line added or removed)")
    n = 0
    for i, (o, c) in enumerate(zip(ol, cl), 1):
        want = E1_TEXT + o if e1_applies(o) else o
        if c != want:
            kind = ("an E1 line left unedited" if c == o else
                    "an edit E1 does not make")
            raise ValueError(f"{name}:{i}: {kind}: {c.decode('ascii', 'replace').rstrip()!r}")
        n += c != o
    if copy != derive(orig):
        raise ValueError(f"{name}: the copy is not derive(original) byte for byte")
    return n


def run(root, out, check_only):
    total = 0
    for src, dst in FILES:
        orig = (root / src).read_bytes()
        target = out / dst
        if not check_only:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(derive(orig))
        n = check_one(dst, orig, target.read_bytes())
        total += n
        print(f"devcopy: {src} blob {git_blob(orig)} -> {dst}: {n} E1 edits, "
              f"no other difference")
    print(f"devcopy: OK, {len(FILES)} files, {total} edits, all of kind E1")


def selftest(root):
    """Plant a fault of each kind the check exists for and require it to be
    refused by name; then require the honest copy to pass."""
    orig = (root / "host/src/bigint.c").read_bytes()
    good = derive(orig)
    plants = {
        "an operator changed": good.replace(b"carry = s >> 32;", b"carry = s >> 31;", 1),
        "an E1 edit missing": good.replace(b"CFT_HD int cft_bn_add(", b"int cft_bn_add(", 1),
        "a line added": good.replace(b"#include \"bigint.h\"\n",
                                     b"#include \"bigint.h\"\n#define X 1\n", 1),
        "a function's body edited": good.replace(b"r->n = 0;\n}", b"r->n = 1;\n}", 1),
    }
    bad = 0
    for what, text in plants.items():
        assert text != good, f"plant '{what}' did not change the copy"
        try:
            check_one("src/bigint.c", orig, text)
            print(f"selftest: plant '{what}' PASSED the check - the check is broken")
            bad += 1
        except ValueError as e:
            print(f"selftest: plant '{what}' refused: {e}")
    print(f"selftest: honest copy: {check_one('src/bigint.c', orig, good)} E1 edits, accepted")
    if bad:
        sys.exit(1)
    print(f"selftest: OK, {len(plants)} plants refused by name")


def main():
    ap = argparse.ArgumentParser()
    here = Path(__file__).resolve().parent
    ap.add_argument("--root", type=Path, default=here.parents[2],
                    help="the tree whose host/ is copied (default: this repo)")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--check-only", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    try:
        if a.selftest:
            selftest(a.root)
        else:
            if a.out is None:
                ap.error("--out is required")
            run(a.root, a.out, a.check_only)
    except ValueError as e:
        print(f"devcopy: REFUSED: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
